@Injectable()
export class SmartAssistantService {
  // ─── Получить сообщение ────────────────────────────────────
  getMessage(
    event: MessageEvent,
    tone: AiTone,
    context?: {
      taskTitle?: string;
      deadlineStr?: string;
      userName?: string;
    },
  ): string {
    const toneTemplates = TEMPLATES[tone] ?? TEMPLATES.FRIENDLY;
    const variants = toneTemplates[event] ?? TEMPLATES.FRIENDLY[event];
    const base = variants[Math.floor(Math.random() * variants.length)];

    return this.injectContext(base, context);
  }

  // ─── Вставка контекста в шаблон ───────────────────────────
  private injectContext(
    template: string,
    ctx?: { taskTitle?: string; deadlineStr?: string; userName?: string },
  ): string {
    if (!ctx) return template;
    let msg = template;
    if (ctx.userName) msg = msg.replace('{name}', ctx.userName);
    return msg;
  }

  // ─── Форматировать полное уведомление ─────────────────────
  formatNotification(
    event: MessageEvent,
    tone: AiTone,
    task: { title: string; deadlineAt?: Date | null; priority: string },
    projectTitle?: string,
    userName?: string,
  ): string {
    const headline = this.getMessage(event, tone, { taskTitle: task.title, userName });

    const lines: string[] = [headline, ''];
    lines.push(`📌 *${task.title}*`);
    if (projectTitle) lines.push(`📂 Проект: ${projectTitle}`);
    if (task.deadlineAt) {
      const d = new Date(task.deadlineAt);
      const fmt = d.toLocaleString('ru-RU', {
        day: '2-digit', month: '2-digit',
        hour: '2-digit', minute: '2-digit',
        timeZone: 'Europe/Moscow',
      });
      lines.push(`📅 Дедлайн: ${fmt} МСК`);
    }
    const priorityEmoji = { LOW: '🔵', MEDIUM: '🟡', HIGH: '🔴', CRITICAL: '⚫' };
    lines.push(`${priorityEmoji[task.priority as keyof typeof priorityEmoji] ?? '⚪'} Приоритет: ${this.priorityLabel(task.priority)}`);

    return lines.join('\n');
  }

  private priorityLabel(p: string): string {
    const map: Record<string, string> = {
      LOW: 'Низкий', MEDIUM: 'Средний', HIGH: 'Высокий', CRITICAL: 'Критический',
    };
    return map[p] ?? p;
  }
}
